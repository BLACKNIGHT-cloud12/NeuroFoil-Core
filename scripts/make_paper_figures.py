#!/usr/bin/env python3
"""
Paper figure and table generator.

Runs after the real-CFD campaign and the Kaggle training run: reads the
dataset artifacts (data/processed/) and the exported surrogate metadata
(models/surrogate_meta.json), and writes vector figures for the manuscript
into paper/figures/. Exits with a clear message when inputs are missing.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

CSV_PATH = PROJECT_ROOT / "data" / "processed" / "airfoil_cfd_dataset.csv"
NPZ_PATH = PROJECT_ROOT / "data" / "processed" / "cp_surface_distributions.npz"
META_PATH = PROJECT_ROOT / "models" / "surrogate_meta.json"
OUT_DIR = PROJECT_ROOT / "paper" / "figures"

MISSING = [p for p in (CSV_PATH, NPZ_PATH) if not p.exists()]


def overview_table(df: pd.DataFrame) -> None:
    """Dataset overview: status distribution, airfoils, Re levels, per-case wall time."""
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    lines = [
        r"% Auto-generated by scripts/make_paper_figures.py — dataset overview",
        r"\begin{table}[h]",
        r"\centering",
        r"\caption{Real-CFD campaign dataset overview.}",
        r"\label{tab:dataset}",
        r"\begin{tabular}{lr}",
        r"\toprule",
        f"Total cases & {len(df)} \\\\",
        f"Distinct airfoils & {df['naca_code'].nunique()} \\\\",
        f"Reynolds levels & {', '.join(f'{v:.0e}' for v in sorted(df['reynolds'].unique()))} \\\\",
        r"\midrule",
    ]
    for status, n in df["status"].value_counts().items():
        lines.append(f"{status} & {n} ({n / len(df) * 100:.1f}\\%) \\\\")
    if "wall_time_s" in df.columns:
        lines.append(f"Median wall-clock per case & {df['wall_time_s'].median():.0f}\\,s \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (OUT_DIR / "table_dataset_overview.tex").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT_DIR / 'table_dataset_overview.tex'}")


def plot_status_by_alpha(df: pd.DataFrame) -> None:
    fig, ax = plt.subplots(figsize=(5, 3))
    alphas = sorted(df["alpha_deg"].unique())
    for status in df["status"].unique():
        frac = [((df["alpha_deg"] == a) & (df["status"] == status)).mean() * 100 for a in alphas]
        ax.plot(alphas, frac, marker="o", label=status)
    ax.set_xlabel("Angle of attack (deg)")
    ax.set_ylabel("Share of cases (%)")
    ax.legend(fontsize=8)
    ax.set_title("Convergence status across the envelope")
    fig.tight_layout()
    fig.savefig(OUT_DIR / "status_by_alpha.pdf")
    plt.close(fig)
    print(f"wrote {OUT_DIR / 'status_by_alpha.pdf'}")


def plot_polar_samples(df: pd.DataFrame) -> None:
    fig, axes = plt.subplots(1, 3, figsize=(11, 3.2))
    for code in sorted(df["naca_code"].unique())[:6]:
        sub = df[(df["naca_code"] == code) & (df["reynolds"] == df["reynolds"].max())]
        sub = sub.sort_values("alpha_deg")
        if len(sub) < 3:
            continue
        axes[0].plot(sub["alpha_deg"], sub["cl"], marker="o", ms=3, label=code)
        axes[1].plot(sub["cd"], sub["cl"], marker="o", ms=3)
        ld = sub["cl"] / sub["cd"].clip(lower=1e-8)
        axes[2].plot(sub["alpha_deg"], ld, marker="o", ms=3)
    axes[0].set(xlabel=r"$\alpha$ (deg)", ylabel=r"$C_L$", title="Lift curves (Re = 6e6)")
    axes[1].set(xlabel=r"$C_D$", ylabel=r"$C_L$", title="Drag polar")
    axes[2].set(xlabel=r"$\alpha$ (deg)", ylabel=r"$L/D$", title="Efficiency")
    axes[0].legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(OUT_DIR / "polar_samples.pdf")
    plt.close(fig)
    print(f"wrote {OUT_DIR / 'polar_samples.pdf'}")


def plot_reynolds_effect(df: pd.DataFrame) -> None:
    fig, ax = plt.subplots(figsize=(5, 3))
    for alpha in sorted(df["alpha_deg"].unique()):
        sub = df[df["alpha_deg"] == alpha].groupby("reynolds")["cd"].mean()
        ax.plot(sub.index / 1e6, sub.values, marker="o", ms=4, label=rf"$\alpha={alpha:+.0f}^\circ$")
    ax.set_xscale("log")
    ax.set_xlabel(r"Reynolds number ($\times 10^6$)")
    ax.set_ylabel(r"Mean $C_D$ (converged cases)")
    ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(OUT_DIR / "reynolds_effect.pdf")
    plt.close(fig)
    print(f"wrote {OUT_DIR / 'reynolds_effect.pdf'}")


def plot_metrics_from_meta() -> None:
    if not META_PATH.exists():
        print(f"[skip] {META_PATH} not found — run the Kaggle training notebook first")
        return
    meta = json.loads(META_PATH.read_text(encoding="utf-8"))
    metrics = meta.get("metrics", {})
    print("recorded metrics:", json.dumps({k: metrics.get(k) for k in sorted(metrics)}, indent=2)[:800])
    print("[note] parity/coverage figures are drawn from notebook outputs; "
          "extend this script once metrics.json cells are fixed in place.")


def main() -> None:
    if MISSING:
        print(f"[skip] dataset not present yet: {[str(m.relative_to(PROJECT_ROOT)) for m in MISSING]}")
        print("       Run the real-CFD campaign first (see RUN_CFD_PACKAGE_README.md).")
        return
    df = pd.read_csv(CSV_PATH)
    if df["reynolds"].nunique() < 2 or df["case_id"].str.contains(r"_c\d+$").all():
        print("[skip] the present dataset is the legacy synthetic placeholder — "
              "run the real-CFD campaign before generating paper figures.")
        return
    overview_table(df)
    plot_status_by_alpha(df)
    plot_polar_samples(df)
    plot_reynolds_effect(df)
    plot_metrics_from_meta()


if __name__ == "__main__":
    main()
