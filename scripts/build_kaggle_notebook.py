                    "# [10.1] Constrained Optimization via SciPy SLSQP & PyTorch Surrogate\n",
                    "from scipy.optimize import minimize\n",
                    "\n",
                    "model_mlp.eval()\n",
                    "mean_cst = np.mean(X[:, 3:-2], axis=0)  # Average CST baseline weights\n",
                    "\n",
                    "def surrogate_predict(m, p, t, alpha, reynolds=6.0e6):\n",
                    "    # Approximate CST weights from m, p, t\n",
                    "    cst_u = mean_cst[:len(mean_cst)//2] + 2.0 * m + 0.5 * (t - 0.12)\n",
                    "    cst_l = mean_cst[len(mean_cst)//2:] - 2.0 * m - 0.5 * (t - 0.12)\n",
                    "    feat = np.concatenate([[m, p, t], cst_u, cst_l, [alpha, reynolds]])\n",
                    "    feat_norm = scaler_x.transform(feat.reshape(1, -1))\n",
                    "    with torch.no_grad():\n",
                    "        pred_norm = model_mlp(torch.tensor(feat_norm, dtype=torch.float32).to(device)).cpu().numpy()\n",
                    "    pred_raw = scaler_y.inverse_transform(pred_norm)[0]\n",
                    "    cl, cd, cm = pred_raw[0], max(pred_raw[1], 1e-5), pred_raw[2]\n",
                    "    return cl, cd, cm\n",
                    "\n",
                    "def objective(x):\n",
                    "    m, p, t, alpha = x\n",
                    "    cl, cd, cm = surrogate_predict(m, p, t, alpha)\n",
                    "    return -(cl / cd)  # Minimize negative L/D\n",
                    "\n",
