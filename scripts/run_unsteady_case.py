"""Unsteady retest of steady-RANS limit-cycle cases (Level-1 hybrid experiment).

Builds a pimpleFoam case on the SAME mesh/BCs as the campaign's steady case and,
optionally, runs it. Purpose: for operating points where steady simpleFoam
limit-cycles, obtain a time-averaged mean plus an unsteadiness band, and verify
the mean is physically well-defined. This is the evidence gate for building the
full hybrid steady/unsteady driver (airfoilHybridFoam).

The steady case dicts are generated by the campaign's own case_builder, then
patched: ddtSchemes Euler, PIMPLE solution block, adjustable time step, and a
fieldAverage function object for the averaging window.

Modes:
  --no-run   build the case only (default; safe while the campaign occupies cores)
  --run      build and execute pimpleFoam (one core; expect ~30-60 min per case)
  --summarize  no build/run: report time-averaged coefficients from a finished run
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

import numpy as np

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from src.cfd.case_builder import OperatingPoint, build_openfoam_case
from src.cfd.mesh_generator import generate_blockmesh_dict, run_blockmesh_and_checkmesh
from src.config import load_config
from src.geometry.naca import generate_naca4_airfoil

CASE_ID_RE = re.compile(r"^NACA(\d{4})_a([+-]\d+\.\d)_Re(\d+e\d+)$")


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Unsteady (pimpleFoam) retest of a campaign case.")
    p.add_argument("case_id", type=str, help="Campaign case id, e.g. NACA0012_a-2.0_Re6e6")
    p.add_argument("--end-time", type=float, default=15.0,
                   help="Physical end time (convective units, chord=1 m, U=1 m/s)")
    p.add_argument("--avg-start", type=float, default=5.0,
                   help="Start of the time-averaging window")
    p.add_argument("--max-co", type=float, default=2.0, help="PIMPLE max Courant number")
    p.add_argument("--output-root", type=Path,
                   default=PROJECT_ROOT / "data" / "unsteady_retest")
    p.add_argument("--run", action="store_true", help="Execute pimpleFoam after building")
    p.add_argument("--summarize", action="store_true",
                   help="Only report averaged coefficients from an existing run")
    p.add_argument("--timeout", type=int, default=14400, help="Solver timeout (s)")
    return p.parse_args()


def build_case(case_id: str, out_dir: Path, end_time: float, avg_start: float,
               max_co: float) -> None:
    m = CASE_ID_RE.match(case_id)
    if not m:
        raise ValueError(f"case_id must look like NACA0012_a-2.0_Re6e6, got {case_id}")
    code, alpha_s, re_s = m.group(1), m.group(2), m.group(3)
    alpha_deg, reynolds = float(alpha_s), float(re_s.replace("e", "e"))

    cfg = load_config()
    mesh_cfg = cfg["mesh"]
    level = mesh_cfg["levels"]["medium"]

    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)

    airfoil = generate_naca4_airfoil(code, num_points=161, closed_te=True)
    airfoil.save_dat(out_dir / "airfoil.dat")
    airfoil.save_metadata(out_dir / "airfoil_meta.json")

    # Mesh with the campaign's adaptive-split fallback semantics.
    mesh_split = 0.30
    meta = generate_blockmesh_dict(
        airfoil=airfoil, case_dir=out_dir, level="medium",
        farfield_radius=float(mesh_cfg["farfield_radius_chords"]),
        wake_length=float(mesh_cfg["wake_length_chords"]),
        span_thickness=float(mesh_cfg["span_thickness_m"]),
        first_cell_height=float(mesh_cfg.get("first_cell_height_m", 4.0e-6)),
        n_airfoil_side=int(level["n_airfoil_side"]),
        n_wake=int(level["n_wake"]), n_normal=int(level["n_normal"]),
        x_split_target=mesh_split,
    )
    stats = run_blockmesh_and_checkmesh(
        case_dir=out_dir, meta=meta,
        wsl_distro=cfg["wsl_environment"]["distro"],
        openfoam_bashrc=cfg["wsl_environment"]["openfoam_bashrc"],
    )
    if not stats.mesh_ok:
        fallback_meta = generate_blockmesh_dict(
            airfoil=airfoil, case_dir=out_dir, level="medium",
            farfield_radius=float(mesh_cfg["farfield_radius_chords"]),
            wake_length=float(mesh_cfg["wake_length_chords"]),
            span_thickness=float(mesh_cfg["span_thickness_m"]),
            first_cell_height=float(mesh_cfg.get("first_cell_height_m", 4.0e-6)),
            n_airfoil_side=int(level["n_airfoil_side"]),
            n_wake=int(level["n_wake"]), n_normal=int(level["n_normal"]),
            x_split_target=0.08,
        )
        fallback_stats = run_blockmesh_and_checkmesh(
            case_dir=out_dir, meta=fallback_meta,
            wsl_distro=cfg["wsl_environment"]["distro"],
            openfoam_bashrc=cfg["wsl_environment"]["openfoam_bashrc"],
        )
        if not fallback_stats.mesh_ok:
            raise RuntimeError(
                f"mesh failed at both splits ({stats.max_non_orthogonality_deg:.2f} / "
                f"{fallback_stats.max_non_orthogonality_deg:.2f} deg)")
        print(f"used fallback split x/c=0.08 "
              f"(non-ortho {fallback_stats.max_non_orthogonality_deg:.2f} deg)")

    # Steady dicts from the campaign's own builder (0/ fields, forceCoeffs, etc.).
    op = OperatingPoint(alpha_deg=alpha_deg, reynolds=reynolds, u_inf=1.0, chord_m=1.0)
    build_openfoam_case(out_dir, op, cfg)

    # Patch to unsteady PIMPLE.
    _patch_control_dict(out_dir, end_time, avg_start, max_co, op.u_inf)
    _patch_fv_schemes(out_dir)
    _patch_fv_solution(out_dir)
    print(f"case built: {out_dir} (pimpleFoam, endTime={end_time}, "
          f"averaging from t={avg_start}, maxCo={max_co})")


def _patch_control_dict(out_dir: Path, end_time: float, avg_start: float,
                        max_co: float, u_inf: float) -> None:
    cd_path = out_dir / "system" / "controlDict"
    text = cd_path.read_text(encoding="utf-8")
    # Keep the generated functions block (forceCoeffs), re-emit the header.
    funcs_idx = text.find("\nfunctions")
    functions_block = text[funcs_idx:] if funcs_idx != -1 else ""
    avg_end = end_time + 1e-4
    field_average = f"""
    fieldAverage1
    {{
        type            fieldAverage;
        libs            (fieldFunctionObjects);
        writeControl    adjustableRunTime;
        writeInterval   {max(1.0, end_time - avg_start):.4f};
        fields          (U p);
        prime2MeanField on;
    }}
}}
"""
    new_text = f"""FoamFile
{{
    version     2.0;
    format      ascii;
    class       dictionary;
    object      controlDict;
}}
application     pimpleFoam;
startFrom       startTime;
startTime       0;
stopAt          endTime;
endTime         {end_time:.4f};
deltaT          1e-05;
writeControl    adjustableRunTime;
writeInterval   2.0;
purgeWrite      2;
writeFormat     ascii;
writePrecision  8;
writeCompression off;
timeFormat      general;
runTimeModifiable yes;
adjustTimeStep  yes;
maxCo           {max_co:.2f};
maxDeltaT       {max_co * 1e-04:.2e};
functions
(
{functions_block}
    fieldAverage1
    {{
        type            fieldAverage;
        libs            (fieldFunctionObjects);
        writeControl    adjustableRunTime;
        writeInterval   {max(1.0, end_time - avg_start):.4f};
        fields          (U p);
        prime2MeanField on;
    }}
);
"""
    # forceCoeffs must start averaging only after avg_start: wrap via its own
    # timeStart using the 'functions' list syntax (already opened above).
    new_text = new_text.replace(
        "        writeControl    timeStep;",
        "        writeControl    adjustableRunTime;\n"
        f"        writeInterval   0.25;\n"
        f"        timeStart       {avg_start:.4f};",
    )
    new_text = new_text.replace(
        f"    fieldAverage1\n    {{\n        type            fieldAverage;\n"
        f"        libs            (fieldFunctionObjects);\n"
        f"        writeControl    adjustableRunTime;\n"
        f"        writeInterval   {max(1.0, end_time - avg_start):.4f};",
        f"    fieldAverage1\n    {{\n        type            fieldAverage;\n"
        f"        libs            (fieldFunctionObjects);\n"
        f"        writeControl    adjustableRunTime;\n"
        f"        writeInterval   {max(1.0, end_time - avg_start):.4f};\n"
        f"        timeStart       {avg_start:.4f};",
        1,
    )
    del avg_end, field_average, functions_block, funcs_idx, text
    cd_path.write_text(new_text, encoding="utf-8")


def _patch_fv_schemes(out_dir: Path) -> None:
    path = out_dir / "system" / "fvSchemes"
    text = path.read_text(encoding="utf-8")
    text = re.sub(r"ddtSchemes\s*\{[^}]*\}",
                  "ddtSchemes\n{\n    default         Euler;\n}", text, count=1)
    path.write_text(text, encoding="utf-8")


def _patch_fv_solution(out_dir: Path) -> None:
    path = out_dir / "system" / "fvSolution"
    text = path.read_text(encoding="utf-8")
    pimple_block = """PIMPLE
{
    momentumPredictor no;
    nOuterCorrectors  2;
    nCorrectors       1;
    nNonOrthogonalCorrectors 1;
}
"""
    text = re.sub(r"SIMPLE\s*\{.*?\n\}\n?", "", text, count=1, flags=re.S)
    # Insert PIMPLE before the first solver sub-dict.
    text = text.replace("\n// * * * * * * * * * * * * * * //\n",
                        "\n// * * * * * * * * * * * * * * //\n", 1)
    insert_at = text.find("\n", text.find("{"))  # after FoamFile header close
    text = text[:insert_at + 1] + "\n" + pimple_block + text[insert_at + 1:]
    path.write_text(text, encoding="utf-8")


def run_case(out_dir: Path, timeout: int) -> int:
    cfg = load_config()
    from src.config import run_solver_command
    openfoam_bashrc = cfg["wsl_environment"]["openfoam_bashrc"]
    cmd = (
        f"source {openfoam_bashrc} >/dev/null 2>&1 && "
        f"cd '{out_dir}' && pimpleFoam > log.pimpleFoam 2>&1"
    )
    proc = run_solver_command(cmd, wsl_distro=cfg["wsl_environment"]["distro"],
                              timeout=timeout)
    print(f"pimpleFoam exit code: {proc.returncode}")
    return proc.returncode


def summarize(out_dir: Path, avg_start: float) -> None:
    cands = list(out_dir.glob("postProcessing/**/coefficient.dat"))
    if not cands:
        raise SystemExit("No coefficient.dat found — run first.")
    arr = np.loadtxt(cands[0], comments="#")
    t, cd_col, cl_col, cm_col = arr[:, 0], arr[:, 1], arr[:, 4], arr[:, 7]
    mask = t >= avg_start
    if mask.sum() < 10:
        raise SystemExit(f"Only {mask.sum()} samples after t={avg_start}.")
    for name, series in (("CL", cl_col), ("CD", cd_col), ("Cm", cm_col)):
        seg = series[mask]
        print(f"{name}: mean={seg.mean():+.5f}  std={seg.std():.2e}  "
              f"p2p={np.ptp(seg):.2e}")
    print(f"averaged over t=[{avg_start}, {t[-1]:.2f}] "
          f"({mask.sum()} samples)")


def main() -> None:
    args = parse_args()
    out_dir = args.output_root / args.case_id
    if args.summarize:
        summarize(out_dir, args.avg_start)
        return
    build_case(args.case_id, out_dir, args.end_time, args.avg_start, args.max_co)
    if args.run:
        run_case(out_dir, args.timeout)
        summarize(out_dir, args.avg_start)


if __name__ == "__main__":
    main()
